/* The Connect editor contract: what the editor in Badger Supports Connect has to offer so that
 * every word, block, room and form on this site can be changed there. Generated from the code that
 * enforces it — the block declarations, the room rules, the form question types and the text
 * registry — so it cannot drift from what the build accepts.
 *
 *   node ops/contract.mjs           # writes docs/CONNECT-EDITOR-CONTRACT.md
 *   node ops/contract.mjs --check   # fails if the file is not what the code says (ops/check.mjs)
 */

import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { BLOCKS } from "../src/render/registry.mjs";
import { QUESTION_TYPES, FORM_SCHEMA } from "../src/shared/forms.mjs";
import { PLACE_SCHEMA } from "../src/render/places.mjs";
import { TEAM_SCHEMA, TEAM_PATH, GROUPS } from "../src/render/team.mjs";
import { placeholders } from "../src/shared/text.mjs";
import { ICONS } from "../src/render/icons.mjs";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const FILE = path.join(ROOT, "docs", "CONNECT-EDITOR-CONTRACT.md");

const FIELD_TYPES = {
  text: "one line of text",
  paragraphs: "one or more paragraphs",
  list: "a short list of words",
  link: "a label and an address (a page on this site, Connect, or another site), and an optional icon",
  "link[]": "several links, in order",
  "media[]": "photos, in order: each a library photo or a pasted link (see Photos)",
  termlist: "rows of a term and its text (and, for topics, an optional link)",
  rows: "doors, each with an id, a title, an icon, optional text, an optional form whose open/closed switch they show, and one link (one door may be marked primary); a door may carry more: a panel under the doors with an anchor, an optional photo, a title, a lead line, lists (each with a label, numbered or ticked, and its items), a closing line and one link",
  circles: "up to three photo circles, each with a photo (a library photo or a pasted link), a label, an address and an icon",
  droplinks: "for a program, the page its Drop in button opens (otherwise it opens the room's directions)",
  embed: "an Instagram reel or post: its address, a title for screen readers, and an optional caption; it loads only when someone presses Play",
  workshops: "workshops, each with an id, a tab name, a title, what the full workshop covers, an optional link, and one activity: a network map (two to four circles, each with ways and examples), bingo (nine squares and a line message), a choice (a scenario, a question, and options each with a verdict), or flip cards (terms and meanings, and a note)",
  cards: "cards, each with an id, a title, short lines shown in bold (a time, a slogan), one quieter line of text, an optional photo (a library photo or a pasted link), an optional icon shown when there is no photo, and an optional link",
  words: "words, in order: each its text, or its `text` and a `size` (1 small, 2 medium, 3 large)",
  qa: "questions with an id, the question, and one or more answer paragraphs",
  points: "short statements, each its `text` and an optional `icon` (see Icons)",
  place: "one published room (content/places)",
  source: "a named data source (events, wall notes, team)",
  teamgroups: "the groups to show, in order: each a group (`directors`, `associate-directors`, `staff`, `volunteers` or `advisors`) and, if it needs one, the heading over it",
  person: "one public profile from Connect, by its address name (`slug`)",
  eventquery: "which events to list: source, program, how many",
  number: "a whole number",
  boolean: "on or off",
  choice: "one of the listed values",
  date: "a calendar date",
};
const fieldType = (spec) => {
  const base = spec.replace(/!$/, "");
  if (base.startsWith("choice:")) return `one of ${base.slice(7).split("|").map((v) => `\`${v}\``).join(", ")}`;
  return FIELD_TYPES[base] || base;
};
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

export function contract() {
  const registry = JSON.parse(fs.readFileSync(path.join(ROOT, "content/text.json"), "utf8"));
  const out = [];
  const w = (s = "") => out.push(s);
  w("# Connect editor contract");
  w();
  w("Generated by `node ops/contract.mjs` from the code the build enforces. Do not edit by hand: `node ops/check.mjs`");
  w("fails when this file and the code disagree. The Exchange request `PUBLIC-SITE-EDITOR-2026-10-20` asks Connect");
  w("for an editor that offers everything below; until it exists, the same records are edited as files in `content/`.");
  w();
  w("Every edit is published as a new version. The build checks a version before anything is published and refuses");
  w("it with the reasons listed, so an editor can show the same reasons before a director presses Publish.");
  w();
  w("## Pages (`bss.page/1`, `content/pages/`)");
  w();
  w("| Field | What it holds |");
  w("|---|---|");
  for (const [f, d] of [
    ["id", "permanent, `pg-…`; never reused"],
    ["path", "the address, starting and ending with `/`"],
    ["aliases", "old addresses that should 301 to this page"],
    ["title, description", "the browser tab and search result"],
    ["analytics", "`public` or `none` (docs/ANALYTICS.md)"],
    ["noindex", "keep this page out of search engines"],
    ["blocks", "the page's blocks, in order; each has a permanent `b-…` id, a type below, and `enabled`"],
  ]) w(`| \`${f}\` | ${d} |`);
  w();
  w("## Blocks");
  w();
  w("Every block can be turned off with `enabled: false`; a block that lists `startsOn` / `endsOn` shows only between those dates.");
  w("Required fields are marked **required**.");
  w();
  for (const b of Object.values(BLOCKS)) {
    w(`### ${b.label} — \`${b.type}\``);
    w();
    w(`Reads: ${b.data.length ? b.data.map((d) => `\`${d}\``).join(", ") : "nothing but its own fields"} · analytics: \`${b.analytics}\` · photos load ${b.loading}${b.client ? ` · browser ${[].concat(b.client).length > 1 ? "modules" : "module"} ${[].concat(b.client).map((c) => `\`${c}\``).join(", ")}` : ""}`);
    w();
    w("| Field | Type | |");
    w("|---|---|---|");
    for (const [name, spec] of Object.entries(b.fields)) w(`| \`${name}\` | ${cell(fieldType(spec))} | ${spec.endsWith("!") ? "**required**" : ""} |`);
    w();
  }
  w("## Icons");
  w();
  w("Wherever a field takes an icon, it is one of these, each with its own small move when its link is pointed at or");
  w(`pressed: ${ICONS.map((i) => `\`${i}\``).join(", ")}. The build refuses any other name.`);
  w();
  w("## Photos");
  w();
  w("Every photo slot — a block's photos, a hero circle, a room, a direction step, an event — takes one of three things:");
  w();
  w("| Form | Example | What happens |");
  w("|---|---|---|");
  w("| a library id | `\"m-people-welcome\"` | the photo in `media/manifest.json`, with its own description and focal point |");
  w("| a link | `\"https://…/photo.jpg\"` | the build fetches the photo once and serves it from this site, never from the link |");
  w("| a link with details | `{ \"link\": \"https://…\", \"alt\": \"…\", \"focal\": [50, 30] }` | the same, with a description and the point (percent across, percent down) to keep in view when it is cropped |");
  w();
  w("A link must start with `https://`. A Google Drive file link works when the file is shared as *Anyone with the link*;");
  w("a Drive folder link is refused. The build refuses a link that does not answer with a photo, and names it. A linked");
  w("photo with no description is read aloud as the text key `media.linkAlt`.");
  w();
  w(`## Rooms and directions (\`${PLACE_SCHEMA}\`, \`content/places/\`)`);
  w();
  w("Adding a room is adding a record. A published room gets its own page at `/directions/<id>/`, appears on");
  w("`/directions/`, and every event held there links to it. A draft (`published: false`) gets no page and no link.");
  w();
  w("| Field | What it holds |");
  w("|---|---|");
  for (const [f, d] of [
    ["id", "permanent; a–z, 0–9 and single hyphens; also the page address"],
    ["published", "on: the room has a page and events link to it"],
    ["name", "**required** — the room, as its page's heading"],
    ["short", "how event lists name it (defaults to name)"],
    ["building, where", "the building, and the floor or room number"],
    ["address", "**required to publish** — the street address; the map button opens it"],
    ["links", "extra links, such as the building's hours"],
    ["photo", "an optional photo of the room (a library photo or a pasted link)"],
    ["steps", "optional — each has a permanent `s-…` id, its text, and an optional photo (a library photo or a pasted link); a room with none shows its address and map button only"],
    ["arrivePhoto", "an optional photo under the last line of the steps, of what a visitor sees on arriving"],
    ["note", "one closing line"],
    ["aliases", "old addresses that should 301 to this room's page"],
  ]) w(`| \`${f}\` | ${d} |`);
  w();
  w(`## Team (Connect's public profiles, \`${TEAM_SCHEMA}\`)`);
  w();
  w("The team is not edited here. Each member writes their own profile in their Connect account and chooses whether it");
  w(`is public; Connect exports the public ones and the build gives each a card on \`${TEAM_PATH}\` and a page of its own`);
  w(`at \`${TEAM_PATH}<slug>/\`. A page only says which groups the Team block shows, in what order, and what to call them.`);
  w("A profile that is not public gets no card and no page. The old addresses under each group 301 to the team page.");
  w();
  w("| Field | What it holds |");
  w("|---|---|");
  for (const [f, d] of [
    ["id", "Connect's opaque id for the profile; never shown"],
    ["slug", "permanent; a–z, 0–9 and single hyphens; the page address"],
    ["published", "on: the member chose a public profile"],
    ["name", "**required** — as the member wants it shown"],
    ["pronouns", "optional"],
    ["classYear, credentials", "optional; a student's class year, or an advisor's credentials"],
    ["title", "**required** — the full title, on the card and the page"],
    ["role", "**required** — Connect's role word"],
    ["group", `**required** — one of ${GROUPS.map((g) => `\`${g}\``).join(", ")}`],
    ["order", "the order within the group"],
    ["bio", "paragraphs the member wrote"],
    ["photo", "a photo the member uploaded to Connect; with none, the card shows their initials"],
    ["contact", "only if the member chose to publish one: a badgersupports.org address"],
    ["aliases", "the member's old address on this site, to 301 to the new one"],
  ]) w(`| \`${f}\` | ${d} |`);
  w();
  w(`## Forms (\`${FORM_SCHEMA}\`, \`content/forms/\`)`);
  w();
  w("Every form has an open/closed switch that the server enforces (a stale tab that sends after closing is refused");
  w("and keeps the answers), a version that rises with every published change, stable question ids, sections that");
  w("may show only when an earlier answer holds, and a workflow (Connect queue, owner, receipt, backup). Question types:");
  w();
  w("| Type | Shows as | Has options | Longest answer |");
  w("|---|---|---|---|");
  for (const [k, v] of Object.entries(QUESTION_TYPES)) w(`| \`${k}\` | ${v.input} | ${v.options ? "yes" : ""} | ${v.max || ""} |`);
  w();
  w("## Every other word (`content/text.json`)");
  w();
  w(`${Object.keys(registry.text).length} keys. Keys are permanent. Required text cannot be published empty and must keep each`);
  w("`{{placeholder}}` its default has; optional text disappears from the page when published empty.");
  w();
  for (const g of registry.groups) {
    const keys = Object.entries(registry.text).filter(([, e]) => e.group === g.id);
    w(`### ${g.label} (${keys.length})`);
    w();
    w("| Key | Default | Where it shows | |");
    w("|---|---|---|---|");
    for (const [k, e] of keys) w(`| \`${k}\` | ${cell(e.text)} | ${cell(e.where)} | ${[e.optional ? "optional" : "", ...placeholders(e.text).map((p) => `\`{{${p}}}\``)].filter(Boolean).join(" ")} |`);
    w();
  }
  w("## Also edited in Connect");
  w();
  w("- **Site settings** (`content/site.json`): menus, the header button, the support line, the footer.");
  w("- **Media library** (`media/manifest.json`): each photo's description (alt text), focal point and provenance. Any slot");
  w("  may instead hold a pasted link (see Photos), so a photo can be swapped without adding it to the library.");
  w("- **Mood check-in** (`content/widgets/mood.json`): the moods, their colours and messages.");
  return out.join("\n") + "\n";
}

if (import.meta.url === url.pathToFileURL(process.argv[1]).href) {
  const text = contract();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(FILE) ? fs.readFileSync(FILE, "utf8") : "";
    if (current !== text) { console.log("docs/CONNECT-EDITOR-CONTRACT.md is out of date: run node ops/contract.mjs"); process.exit(1); }
    console.log("docs/CONNECT-EDITOR-CONTRACT.md is current");
  } else {
    fs.mkdirSync(path.dirname(FILE), { recursive: true });
    fs.writeFileSync(FILE, text);
    console.log(`wrote docs/CONNECT-EDITOR-CONTRACT.md (${text.split("\n").length} lines)`);
  }
}
